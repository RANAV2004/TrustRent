from datetime import datetime, timezone
from sqlalchemy import JSON, Boolean, Column, DateTime, Float, ForeignKey, Integer, String, Text
from app.core.database import Base
def utcnow() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None)
class Listing(Base):  # listing
    __tablename__ = "listings"
    id = Column(String(16), primary_key=True)
    owner_id = Column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    title = Column(String(120), nullable=False)
    address = Column(String(300), nullable=True)
    locality = Column(String(80), nullable=False, index=True)
    city = Column(String(60), nullable=False, index=True)
    pincode = Column(String(6), nullable=False, index=True)
    lat = Column(Float, nullable=False)
    lng = Column(Float, nullable=False)
    show_exact_location = Column(Boolean, default=False)
    rent = Column(Integer, nullable=False)
    deposit = Column(Integer, nullable=False)
    bhk = Column(Integer, nullable=False)
    furnishing = Column(String(20), nullable=False)
    area_sqft = Column(Integer, default=0)
    amenities = Column(JSON, default=list)
    preferred_tenants = Column(JSON, default=list)
    available_from = Column(String(10), nullable=False)
    min_months = Column(Integer, default=11)
    max_months = Column(Integer, default=22)
    description = Column(Text, nullable=True)
    about_owner = Column(Text, nullable=True)
    photos = Column(JSON, default=list)
    status = Column(String(10), default="live")
    admin_note = Column(Text, nullable=True)
    tenancies_completed = Column(Integer, default=0)
    full_refunds = Column(Integer, default=0)
    disputes_lost = Column(Integer, default=0)
    listed_at = Column(DateTime, default=utcnow)
    listed_days_ago = Column(Integer, nullable=True)
class OwnerApplication(Base):  # owner verify
    __tablename__ = "owner_applications"
    user_id = Column(String(36), ForeignKey("users.id"), primary_key=True)
    status = Column(String(12), default="submitted")
    relation = Column(String(12), nullable=False)
    id_doc_type = Column(String(60), nullable=False)
    id_file_name = Column(String(255), nullable=False)
    id_file_path = Column(String(500), nullable=False)
    id_file_iv = Column(String(64), nullable=False)
    id_file_hash = Column(String(66), nullable=False)
    property_doc_type = Column(String(80), nullable=False)
    property_file_name = Column(String(255), nullable=False)
    property_file_path = Column(String(500), nullable=False)
    property_file_iv = Column(String(64), nullable=False)
    property_file_hash = Column(String(66), nullable=False)
    property_address = Column(String(300), nullable=False)
    submitted_at = Column(DateTime, default=utcnow)
    reviewed_at = Column(DateTime, nullable=True)
    reviewed_by = Column(String(36), nullable=True)
    review_note = Column(String(500), nullable=True)
class Conversation(Base):  # chat
    __tablename__ = "conversations"
    id = Column(String(36), primary_key=True)
    listing_id = Column(String(16), ForeignKey("listings.id"), nullable=False, index=True)
    seeker_id = Column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    owner_id = Column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    created_at = Column(DateTime, default=utcnow)
    updated_at = Column(DateTime, default=utcnow)
    seeker_last_read = Column(DateTime, nullable=True)
    owner_last_read = Column(DateTime, nullable=True)
class Message(Base):  # message
    __tablename__ = "messages"
    id = Column(String(36), primary_key=True)
    conversation_id = Column(String(36), ForeignKey("conversations.id"), nullable=False, index=True)
    sender_id = Column(String(36), ForeignKey("users.id"), nullable=False)
    kind = Column(String(8), default="text")
    text = Column(Text, nullable=True)
    visit_slots = Column(JSON, nullable=True)
    visit_status = Column(String(10), nullable=True)
    accepted_slot = Column(String(40), nullable=True)
    created_at = Column(DateTime, default=utcnow)
class EmailVerification(Base):  # email code
    __tablename__ = "email_verification_codes"
    email = Column(String(255), primary_key=True)
    code_hash = Column(String(128), nullable=False)
    expires_at = Column(DateTime, nullable=False)
    attempts = Column(Integer, default=0)
class IdentitySubmission(Base):  # id document
    __tablename__ = "identity_submissions"
    id = Column(String(36), primary_key=True)
    user_id = Column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    doc_type = Column(String(60), nullable=False)
    file_name = Column(String(255), nullable=False)
    file_path = Column(String(500), nullable=False)
    file_iv = Column(String(64), nullable=False)
    file_hash = Column(String(66), nullable=False)
    status = Column(String(12), default="pending")
    submitted_at = Column(DateTime, default=utcnow)
    reviewed_at = Column(DateTime, nullable=True)
    reviewed_by = Column(String(120), nullable=True)
    review_note = Column(String(500), nullable=True)
